/** Список порогів для цього курсу — порожньо, якщо мотивацію вимкнено. */
export function courseStreakMessages(course) {
  return Array.isArray(course?.streakMessages) ? course.streakMessages : [];
}

/**
 * "Кругла" віха загальної серії: 2, 5, 10, а далі кожні 5 — не кожне число
 * поспіль, інакше на довгому прогоні (20-30 питань підряд) тост вилітав би
 * щоразу і набридав.
 */
export function isScheduledStreak(streak) {
  if (streak === 2 || streak === 5 || streak === 10) return true;
  return streak > 10 && streak % 5 === 0;
}

/**
 * Яке повідомлення (якщо є) показати за поточну серію streak. Точний
 * threshold — своя картинка/текст (2..10). Усе понад 10, що не влучило в
 * жоден прописаний поріг (11, 13, 14, 15, 20, 30... — або "рідна" довжина
 * ідеально пройденого блоку питань), перевикористовує повідомлення
 * threshold:12 із {n}-підстановкою реального значення — не бракує окремого
 * тексту для кожної можливої довжини блоку/серії.
 */
export function pickStreakMessage(streak, messages) {
  if (!Array.isArray(messages) || messages.length === 0) return null;
  const exact = messages.find((m) => m.threshold === streak);
  if (exact) return exact;
  if (streak > 10) return messages.find((m) => m.threshold === 12) || null;
  return null;
}

export function resolveStreakSub(message, streak) {
  return (message?.sub || "").replace("{n}", streak);
}
