/**
 * Геометрія «дороги» плану курсу (components/CoursePlan.tsx, 2026-09-17,
 * четверта ітерація): суцільний SVG-шлях крізь центри маленьких крапок-
 * станцій (не крізь самі великі кружечки статусу — крапка сидить ВИЩЕ за
 * великий кружечок, з'єднана з ним короткою "ніжкою"; так лінія ніколи не
 * зливається з рамкою картки, скарга користувача).
 *
 * Чиста функція без DOM і без React — координати вузлів вимірюються в
 * компоненті (реальні позиції карток після верстки, бо кількість колонок
 * залежить від ширини екрана й наперед невідома), сюди приходять уже
 * готовими точками. Це дозволяє покрити геометрію тестами без браузера.
 *
 * ВАЖЛИВО про перехід рядка (реальний баг, знайдений користувачем: лінія
 * ховалась ПІД карткою). Раніше середина переходу рахувалась як просте
 * середнє Y двох сусідніх вузлів — а це залежить від ВИСОТИ картки: коли
 * картка вища за проміжок між рядками (майже завжди, особливо для
 * прямокутних карток), та середина потрапляє ВСЕРЕДИНУ картки, а не в
 * порожній проміжок між рядками, і горизонтальна ділянка шляху йде ПІД
 * сусідніми картками того самого ряду (z-index картки вищий за z-index
 * SVG — лінія стає невидимою).
 * Правильна середина — це середина між СПРАВЖНІМИ межами вільного
 * проміжку: низом картки попереднього ряду (`rowBottom`) і висотою
 * станції наступного ряду (`y` наступної точки). Ці дві межі залежать
 * лише від сталих CSS-відступів (row-gap, зсув крапки над карткою), а НЕ
 * від висоти конкретної картки — тому цей проміжок завжди дійсно вільний,
 * незалежно від того, скільки тексту в картці.
 */

export type SnakePoint = {
  x: number;
  /** Y-координата станції (маленької крапки, через яку йде лінія) — НЕ
   *  верх картки і не центр великого кружечка статусу. */
  y: number;
  /** Y-координата НИЗУ картки цього ряду. Потрібна лише для розрахунку
   *  переходу на наступний ряд — знайти справжній вільний проміжок між
   *  рядками, а не середину відстані між станціями (яка залежить від
   *  висоти картки й могла б опинитись усередині неї). */
  rowBottom: number;
};

const ROW_EPS = 1; // px — допуск на субпіксельні відхилення виміру DOM

function sameRow(a: SnakePoint, b: SnakePoint): boolean {
  return Math.abs(a.y - b.y) <= ROW_EPS;
}

function fmt(n: number): number {
  return Math.round(n * 100) / 100;
}

/**
 * SVG `d` для шляху крізь усі передані точки в порядку проходження курсу.
 * Порожній рядок для 0 або 1 точки (лінія в такому разі не потрібна).
 *
 * @param cornerRadius бажаний радіус заокруглення кутів переходу рядка —
 *   фактичний радіус клампується під реальний вільний проміжок між
 *   рядками, щоб на тісній сітці маршрут не перетинав сам себе.
 */
export function buildSnakePath(points: SnakePoint[], cornerRadius = 10): string {
  if (points.length < 2) return "";

  // Передпрохід: групуємо точки по рядках і для кожного рядка беремо
  // МАКСИМУМ rowBottom серед усіх його точок — не лише останньої перед
  // переносом. Картки в одному ряду тепер можуть мати РІЗНУ висоту
  // (ширина/висота картки за контентом, flex-wrap, не CSS grid із
  // примусовим вирівнюванням), тож якщо взяти rowBottom лише останньої
  // картки ряду, а сусідня картка того самого ряду виявиться вищою —
  // горизонтальна ділянка переходу знову опиниться під ЦІЄЮ сусідньою
  // карткою (той самий клас бага, що й раніше, тільки тригер інший).
  const rowOf: number[] = [0];
  const rowMaxBottom: number[] = [points[0].rowBottom];
  for (let i = 1; i < points.length; i += 1) {
    const idx = sameRow(points[i - 1], points[i]) ? rowOf[i - 1] : rowOf[i - 1] + 1;
    rowOf.push(idx);
    rowMaxBottom[idx] = Math.max(rowMaxBottom[idx] ?? -Infinity, points[i].rowBottom);
  }

  const cmds: string[] = [`M ${fmt(points[0].x)} ${fmt(points[0].y)}`];

  for (let i = 1; i < points.length; i += 1) {
    const prev = points[i - 1];
    const cur = points[i];

    if (sameRow(prev, cur)) {
      cmds.push(`L ${fmt(cur.x)} ${fmt(cur.y)}`);
      continue;
    }

    const dx = cur.x - prev.x;
    // Справжній вільний проміжок: від НАЙНИЖЧОЇ картки попереднього ряду
    // (rowMaxBottom, не prev.rowBottom — див. коментар вище) до станції
    // наступного ряду.
    const gapTop = rowMaxBottom[rowOf[i - 1]];
    const gapBottom = cur.y;

    if (Math.abs(dx) < ROW_EPS || gapBottom <= gapTop) {
      // Однакова X (сітка в одну колонку, мобільний телефон) АБО проміжку
      // між рядками фактично немає (тісна верстка) — пряма лінія без
      // заокруглень, нема що згладжувати.
      cmds.push(`L ${fmt(cur.x)} ${fmt(cur.y)}`);
      continue;
    }

    const midY = (gapTop + gapBottom) / 2;
    const r = Math.max(0, Math.min(cornerRadius, (gapBottom - gapTop) / 2, Math.abs(dx) / 2));
    const dir = Math.sign(dx);

    // Вниз від prev до першого закруглення.
    cmds.push(`L ${fmt(prev.x)} ${fmt(midY - r)}`);
    cmds.push(`Q ${fmt(prev.x)} ${fmt(midY)} ${fmt(prev.x + dir * r)} ${fmt(midY)}`);
    cmds.push(`L ${fmt(cur.x - dir * r)} ${fmt(midY)}`);
    cmds.push(`Q ${fmt(cur.x)} ${fmt(midY)} ${fmt(cur.x)} ${fmt(midY + r)}`);
    cmds.push(`L ${fmt(cur.x)} ${fmt(cur.y)}`);
  }

  return cmds.join(" ");
}

/**
 * Шлях зеленого прогресу — від початку до індексу stopIndex ВКЛЮЧНО
 * (лінія «впирається» у вузол наступного непройденого/закритого модуля,
 * а не зупиняється перед ним). stopIndex <= 0 — прогресу немає (нічого не
 * складено), порожній рядок: сама лінія в такому разі не потрібна, колір
 * вузла й так показує стан.
 */
export function buildProgressPath(points: SnakePoint[], stopIndex: number, cornerRadius = 10): string {
  if (stopIndex <= 0) return "";
  return buildSnakePath(points.slice(0, stopIndex + 1), cornerRadius);
}
