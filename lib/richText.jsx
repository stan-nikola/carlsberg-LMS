/**
 * Мінімальний безпечний рендер тексту курсу (без dangerouslySetInnerHTML
 * і без залежності від markdown-парсера) — легасі-контент курсів був з
 * <b>, тут той самий ефект через розмітку зірочками. Розбиває на
 * параграфи по порожньому рядку.
 *
 * Підтримується три накреслення — рівно ті, для яких у конструкторі є
 * кнопки (components/AdminCourseEditor.jsx, RichTextArea):
 *   **текст**  → жирний
 *   *текст*    → курсив
 *   __текст__  → підкреслений
 *
 * Підкреслення позначається саме `__`, а не як у класичному markdown
 * (де `__` — це другий спосіб написати жирний): підкресленого накреслення
 * в markdown немає взагалі, а `__` — найближчий звичний для ока знак і
 * не конфліктує із зірочками.
 */

// Порядок альтернатив важливий: **жирний** мусить перевірятись ДО
// *курсиву*, інакше подвійні зірочки розпадуться на два курсиви.
//
// Курсив і підкреслення вимагають, щоб одразу після відкривного знака й
// перед закривним стояв НЕ пробіл — інакше рядок-перелік на кшталт
// "* пункт один * пункт два" перетворився б на курсив. Для **жирного**
// цієї вимоги свідомо немає: він працював так з самого початку, і
// вузьким правилом можна було б зламати вже збережений контент.
const INLINE_TOKEN =
  /(\*\*\*[^*\n]+\*\*\*|\*\*[^*\n]+\*\*|__[^\s_][^_\n]*[^\s_]__|__[^\s_]__|\*[^\s*][^*\n]*[^\s*]\*|\*[^\s*]\*)/g;

/**
 * Вміст кожного знайденого фрагмента розбирається РЕКУРСИВНО — інакше
 * поєднання накреслень показувало б співробітнику сирі знаки розмітки.
 * Натиснути в конструкторі Ж, а потім К на тому самому слові — звична
 * дія, і вона дає `***слово***`; так само `__**слово**__` для
 * підкресленого жирного. Рекурсія завершується завжди: вміст коротший
 * за сам фрагмент, а текст без розмітки split лишає як є.
 */
function renderInline(text, keyPrefix = "") {
  return text.split(INLINE_TOKEN).map((chunk, idx) => {
    const key = `${keyPrefix}${idx}`;

    const boldItalic = chunk.match(/^\*\*\*([^*\n]+)\*\*\*$/);
    if (boldItalic) {
      return (
        <strong key={key}>
          <em>{renderInline(boldItalic[1], `${key}-`)}</em>
        </strong>
      );
    }

    const bold = chunk.match(/^\*\*([^*\n]+)\*\*$/);
    if (bold) return <strong key={key}>{renderInline(bold[1], `${key}-`)}</strong>;

    const underline = chunk.match(/^__([^_\n]+)__$/);
    if (underline) return <u key={key}>{renderInline(underline[1], `${key}-`)}</u>;

    const italic = chunk.match(/^\*([^*\n]+)\*$/);
    if (italic) return <em key={key}>{renderInline(italic[1], `${key}-`)}</em>;

    return chunk;
  });
}

export function renderRichText(text) {
  if (!text) return null;
  return text.split(/\n\n+/).map((paragraph, pIdx) => <p key={pIdx}>{renderInline(paragraph)}</p>);
}

/**
 * Ті самі накреслення, але БЕЗ розбиття на абзаци — для місць, де текст
 * уже лежить усередині свого рядкового контейнера (`<p class="cp-lead">`,
 * `<span class="q-fb-explain">`, репліка діалогу). Там renderRichText дав
 * би <p> усередині <p>: браузер такий тег розриває, і React скаржиться на
 * гідратацію. У конструкторі такі поля йдуть без підказки про абзац
 * (`paragraphs={false}` у RichTextArea) — щоб автор не чекав від порожнього
 * рядка того, чого тут не станеться.
 */
export function renderRichMarks(text) {
  if (!text) return null;
  return renderInline(text);
}
